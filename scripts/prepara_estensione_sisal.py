"""Genera il lettore dell'estensione dallo stesso estrattore usato da Selenium."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from acquisition.sisal import DOM_SCRIPT


def main():
    source = DOM_SCRIPT.replace('text:document.body.innerText,', '')
    # Extension in a personal browser: never include full page text or navigation links.
    source = source.replace("links:[...document.querySelectorAll('a[href]')].filter(visible).map(e=>({url:e.href,text:norm(text(e))}))", 'links:[]')
    wrapper = """/* Generated by scripts/prepara_estensione_sisal.py. Do not edit directly. */
'use strict';
globalThis.SisalReader = {capture() {
  const data = (() => {
__READER__
  })();
  const url = new URL(location.href);
  data.source_url = url.origin + url.pathname;
  delete data.links; delete data.title;
  data.headings = data.headings.filter(s=>/\\s[–—-]\\s|\\svs\\.?\\s|tiri/i.test(s));
  data.frame_hosts = [...document.querySelectorAll('iframe[src]')].map(f=>{
    try{return new URL(f.src).hostname}catch(_){return ''}
  }).filter(Boolean);
  data.observed_at = new Date().toISOString();
  return data;
}};
"""
    output = Path(__file__).resolve().parents[1] / 'extensions/sisal-quotes/reader.js'
    output.write_text(wrapper.replace('__READER__', source), encoding='utf-8')
    print(output)


if __name__ == '__main__':
    main()
